use super::*;
use rune::{Env, Key, KeyEvent, Mods, Runtime};

pub(super) fn runtime(source: &str, mode: app::Mode) -> Runtime<State> {
    let mut s = State::new();
    s.headless = true;
    s.docs.clear();
    s.blank();
    s.doc_mut().edit = rune::TextEdit::new(source);
    s.doc_mut().edit.set_caret(0);
    s.doc_mut().original = source.into();
    s.mode = mode;
    let mut rt = Runtime::new(
        s,
        ui::view,
        (1060.0, 780.0),
        Env {
            system_dark: false,
            scale: 1.0,
        },
    );
    rt.on_key = Some(app::on_key);
    rt.poll = Some(app::poll);
    rt.set_modifier_keys(true);
    rt.frame(0.0);
    rt
}
pub(super) fn click(rt: &mut Runtime<State>, key: &str) {
    let (x, y) = rt.find(key).unwrap_or_else(|| panic!("missing {key}"));
    rt.pointer_down(x, y);
    rt.pointer_up(x, y);
    rt.frame(1.0 / 60.0);
}

#[test]
fn new_from_welcome_reuses_the_placeholder_but_preserves_existing_work() {
    let mut rt = runtime("", app::Mode::Preview);
    click(&mut rt, "new-document");
    assert_eq!(rt.state.docs.len(), 1);
    assert!(rt.state.mode == app::Mode::Edit);
    rt.paste("My new document");
    rt.frame(0.0);
    // This is the same action registered as the native File → New / ⌘N command.
    rt.update(app::new_document);
    rt.frame(0.0);
    assert_eq!(rt.state.docs.len(), 2);
    assert_eq!(rt.state.docs[0].edit.text, "My new document");
    assert!(rt.state.doc().edit.text.is_empty());
}

#[test]
fn command_new_from_welcome_and_from_an_empty_saved_file() {
    let mut rt = runtime("", app::Mode::Preview);
    rt.update(app::new_document);
    rt.frame(0.0);
    assert_eq!(rt.state.docs.len(), 1);
    assert!(rt.state.mode == app::Mode::Edit);
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("empty.md");
    std::fs::write(&path, "").unwrap();
    rt.update(|s, _| s.open(&path));
    rt.frame(0.0);
    rt.update(app::new_document);
    rt.frame(0.0);
    assert_eq!(rt.state.docs.len(), 2);
    assert!(rt.state.docs[0].path.is_some());
    assert!(rt.state.doc().path.is_none());
}

#[test]
fn split_editor_typing_updates_the_document_and_survives_view_changes_and_undo() {
    let mut rt = runtime("# Before\n", app::Mode::Preview);
    click(&mut rt, "view-mode/segment2");
    assert!(rt.state.mode == app::Mode::Split);
    rt.update(|_, tx| tx.focus("editor", false));
    rt.frame(0.0);
    rt.paste("# Inserted\n");
    rt.frame(0.0);
    assert_eq!(rt.state.doc().edit.text, "# Inserted\n# Before\n");
    assert!(rt.state.doc().dirty());
    click(&mut rt, "view-mode/segment0");
    assert!(rt.find("markdown").is_some());
    click(&mut rt, "view-mode/segment1");
    rt.update(|_, tx| tx.focus("editor", false));
    rt.frame(0.0);
    rt.key(KeyEvent {
        key: Key::Command('z'),
        mods: Mods {
            cmd: true,
            logo: true,
            ..Default::default()
        },
    });
    rt.frame(0.0);
    assert_eq!(rt.state.doc().edit.text, "# Before\n");
    assert!(!rt.state.doc().dirty());
}

#[test]
fn task_click_rewrites_only_the_checkbox_character_and_toggles_back() {
    let mut rt = runtime("- [ ] Ship it\n", app::Mode::Preview);
    // The accessible checkbox is generated by Rune's Markdown parser, not by the app.
    let tree = rt.accessibility_json();
    fn checkbox(v: &serde_json::Value) -> Option<String> {
        if v["role"] == "check-box" {
            return v["key"].as_str().map(str::to_owned);
        }
        if let Some(items) = v.as_array() {
            for item in items {
                if let Some(k) = checkbox(item) {
                    return Some(k);
                }
            }
        }
        if let Some(items) = v.as_object() {
            for item in items.values() {
                if let Some(k) = checkbox(item) {
                    return Some(k);
                }
            }
        }
        None
    }
    let key = checkbox(&tree).unwrap_or_else(|| panic!("no checkbox in {tree}"));
    click(&mut rt, &key);
    assert_eq!(rt.state.doc().edit.text, "- [x] Ship it\n");
    click(&mut rt, &key);
    assert_eq!(rt.state.doc().edit.text, "- [ ] Ship it\n");
}

#[test]
fn search_matches_across_markdown_emphasis_and_selects_the_source_in_edit_mode() {
    let mut rt = runtime(
        "Hello **beautiful** world\n\nBeautiful things",
        app::Mode::Split,
    );
    rt.update(|s, tx| {
        s.finding = true;
        s.search.replace_text("beautiful world");
        s.refresh_search();
        s.show_match(tx);
    });
    rt.frame(0.0);
    assert_eq!(rt.state.matches.len(), 1);
    assert_eq!(rt.state.doc().edit.selected(), "beautiful** world");
    rt.update(|s, tx| {
        s.search.replace_text("beautiful");
        s.refresh_search();
        s.find_step(true, tx);
    });
    rt.frame(0.0);
    assert_eq!(rt.state.matches.len(), 2);
    assert_eq!(rt.state.match_index, 1);
    assert_eq!(rt.state.doc().edit.selected(), "Beautiful");
}

#[test]
fn opening_another_file_preserves_dirty_text_and_deduplicates_paths() {
    let mut rt = runtime("Unsaved work", app::Mode::Edit);
    rt.state.doc_mut().edit.insert("new ");
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("read me.md");
    std::fs::write(&path, "# On disk").unwrap();
    rt.update(|s, _| s.open(&path));
    rt.frame(0.0);
    assert_eq!(rt.state.docs.len(), 2);
    assert_eq!(rt.state.docs[0].edit.text, "new Unsaved work");
    rt.update(|s, _| s.open(&path));
    rt.frame(0.0);
    assert_eq!(rt.state.docs.len(), 2);
}
